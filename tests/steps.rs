#[test]
fn script_runs_under_sh() {
    let steps = vec![step(&["printf", "%s\n", "it's $HOME; ok"])];
    let output = Command::new("sh")
        .arg("-c")
        .arg(shell_script(&steps))
        .output()
        .unwrap();
    assert!(output.status.success());
    assert_eq!(output.stdout, b"it's $HOME; ok\n");
}

